#!/bin/bash
set -euo pipefail
# Four-node launcher for offline OPD phases.
# Usage: bash start-offline-opd.sh phase1|phase2|phase3 [--bg]

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)"
SLIME_DIR="${SLIME_DIR:-$(cd "${SCRIPT_DIR}/../../../.." && pwd)}"
SLIME_PYTHON="${SLIME_VENV:-${SLIME_DIR}/.slime_venv}/bin/python3"
[[ -x "${SLIME_PYTHON}" ]] || SLIME_PYTHON=python3
PHASE="${1:?usage: start-offline-opd.sh phase1|phase2|phase3 [--bg]}"
BACKGROUND="${2:-}"
if [[ -n "${OFFLINE_OPD_RUN_SCRIPT_OVERRIDE:-}" ]]; then
   OFFLINE_OPD_RUN_SCRIPT="${OFFLINE_OPD_RUN_SCRIPT_OVERRIDE}"
else
   case "${PHASE}" in
      phase1) OFFLINE_OPD_RUN_SCRIPT="${SCRIPT_DIR}/run-student_dump.sh" ;;
      phase2) OFFLINE_OPD_RUN_SCRIPT="${SCRIPT_DIR}/run_phase2.sh" ;;
      phase3) OFFLINE_OPD_RUN_SCRIPT="${SCRIPT_DIR}/run-offline_train.sh" ;;
      *) echo "unknown phase: ${PHASE}" >&2; exit 2 ;;
   esac
fi
export OFFLINE_OPD_RUN_SCRIPT

: "${PADDLE_TRAINERS:?PADDLE_TRAINERS is not set}"
: "${PADDLE_TRAINERS_NUM:?PADDLE_TRAINERS_NUM is not set}"
NNODES="${PADDLE_TRAINERS_NUM}"
export MASTER_ADDR="${MASTER_ADDR:-${PADDLE_TRAINERS%%,*}}"
export RUN_TAG="${RUN_TAG:-$(TZ='Asia/Shanghai' date +%Y%m%d_%H%M%S)}"
export MEGATRON_LM_PATH="${MEGATRON_LM_PATH:-/path/to/workspace/env_run/<user>/Megatron-LM}"
export HF_CHECKPOINT="${HF_CHECKPOINT:-/path/to/SFT/results/qwen35-9b-scaleswe5000-sft-246step-add-finish/checkpoint-246}"
export LOAD_PATH="${LOAD_PATH:-/path/to/OPD/model/qwen35-9b-scaleswe5000-sft-246-add-finish_torch_dist}"
export TEACHER_MODEL="${TEACHER_MODEL:-/path/to/SFT/model/Qwen3.6-27B}"
export OPD_ID_TOPK="${OPD_ID_TOPK:-1024}"
export OFFLINE_OPD_LOSS_TYPE="${OFFLINE_OPD_LOSS_TYPE:-topk_reverse_kl}"
export SAVE_INTERVAL="${SAVE_INTERVAL:-30}"

# Teacher scoring is materialized once. For Phase 3, replay those fixed scored
# artifacts for ten epochs by default through a generated replay directory.
TRAIN_EPOCHS="${TRAIN_EPOCHS:-10}"
EPOCH_SHUFFLE="${EPOCH_SHUFFLE:-1}"
if [[ "${PHASE}" == phase3 ]]; then
   : "${SCORED_DIR:?set SCORED_DIR to the one-pass Phase-2 scored directory}"
   [[ "${TRAIN_EPOCHS}" =~ ^[1-9][0-9]*$ ]] || { echo "TRAIN_EPOCHS must be a positive integer: ${TRAIN_EPOCHS}" >&2; exit 1; }
   [[ "${EPOCH_SHUFFLE}" == 0 || "${EPOCH_SHUFFLE}" == 1 ]] || { echo "EPOCH_SHUFFLE must be 0 or 1" >&2; exit 1; }
   NEED_FANOUT=0
   (( TRAIN_EPOCHS > 1 )) && NEED_FANOUT=1
   [[ -n "${TRAIN_STEPS:-}" ]] && NEED_FANOUT=1
   SOURCE_BATCH_SIZE=""
   if [[ -n "${ROLLOUT_BATCH_SIZE:-}" ]]; then
      [[ "${ROLLOUT_BATCH_SIZE}" =~ ^[1-9][0-9]*$ ]] || {
         echo "ROLLOUT_BATCH_SIZE must be a positive integer: ${ROLLOUT_BATCH_SIZE}" >&2
         exit 1
      }
      SOURCE_BATCH_SIZE="$("${SLIME_PYTHON}" - "${SCORED_DIR}/rollout_0.pt" <<'PY'
import sys, torch
blob = torch.load(sys.argv[1], weights_only=False)
if blob.get("format") in {"offline_opd_sample_manifest_v1", "offline_opd_sample_manifest_v2"}:
    print(len(blob["sample_files"]))
else:
    print(len(blob["samples"]))
PY
)"
   fi
   # A one-epoch Phase 3 still needs a generated stream when its training batch
   # differs from the Phase-2 manifest batch (including a padded final batch).
   if (( NEED_FANOUT == 0 )) && [[ -n "${SOURCE_BATCH_SIZE}" ]]; then
      (( ROLLOUT_BATCH_SIZE != SOURCE_BATCH_SIZE )) && NEED_FANOUT=1
   fi
   if (( NEED_FANOUT == 1 )); then
      if [[ -z "${FANOUT_DIR:-}" ]]; then
         if [[ -n "${SOURCE_BATCH_SIZE}" ]] && (( ROLLOUT_BATCH_SIZE != SOURCE_BATCH_SIZE )); then
            FANOUT_DIR="${SCORED_DIR}/epochs_x${TRAIN_EPOCHS}_b${ROLLOUT_BATCH_SIZE}"
         else
            FANOUT_DIR="${SCORED_DIR}/epochs_x${TRAIN_EPOCHS}"
         fi
         [[ -n "${TRAIN_STEPS:-}" ]] && FANOUT_DIR="${FANOUT_DIR}_s${TRAIN_STEPS}"
      fi
      TRAIN_STEPS="${TRAIN_STEPS:-}" SHUFFLE="${EPOCH_SHUFFLE}" bash "${SCRIPT_DIR}/fanout_epochs.sh" \
         "${SCORED_DIR}" "${TRAIN_EPOCHS}" "${FANOUT_DIR}"
      export SCORED_DIR="$(cd "${FANOUT_DIR}" && pwd)"
   fi
fi

[[ -r "${OFFLINE_OPD_RUN_SCRIPT}" ]] || { echo "run script missing: ${OFFLINE_OPD_RUN_SCRIPT}" >&2; exit 1; }
[[ -x "${SCRIPT_DIR}/_rank_dispatch.sh" ]] || { echo "dispatcher is not executable" >&2; exit 1; }
if [[ "${PHASE}" == phase1 || "${PHASE}" == phase3 ]]; then
   [[ -d "${MEGATRON_LM_PATH}" ]] || { echo "MEGATRON_LM_PATH not found: ${MEGATRON_LM_PATH}" >&2; exit 1; }
   [[ -d "${HF_CHECKPOINT}" ]] || { echo "HF_CHECKPOINT not found: ${HF_CHECKPOINT}" >&2; exit 1; }
   [[ -d "${LOAD_PATH}" ]] || { echo "LOAD_PATH not found: ${LOAD_PATH}" >&2; exit 1; }
fi
if [[ "${PHASE}" == phase2 && "${SKIP_SERVE:-0}" -ne 1 ]]; then
   [[ -d "${TEACHER_MODEL}" ]] || { echo "TEACHER_MODEL not found: ${TEACHER_MODEL}" >&2; exit 1; }
fi

CMD=(
   mpirun -n "${NNODES}" -N 1
   -x PADDLE_TRAINERS -x PADDLE_TRAINERS_NUM -x MASTER_ADDR -x OFFLINE_OPD_RUN_SCRIPT
)

# Only export variables that exist. This keeps phase-specific settings optional while
# preserving the no-whitespace dispatcher required by this cluster's mpirun wrapper.
FORWARDED_VARS=(
   MEGATRON_LM_PATH SLIME_VENV RUN_TAG RUN_DIR HF_CHECKPOINT LOAD_PATH SAVE_PATH SAVE_INTERVAL MODEL_ARGS_SH
   PROMPT_DATA DUMP_DIR SCORED_DIR IN_DIR OUT_DIR OPD_ID_TOPK OFFLINE_OPD_LOSS_TYPE START_ROLLOUT_ID
   OPD_TEACHER_CACHE_TOPK OPD_DYNAMIC_SUPPORT_TOPK OPD_TEACHER_CACHE_H2D_ROWS
   OPD_FORWARD_KL_COEF OPD_REVERSE_KL_COEF OPD_FORWARD_KL_ANNEAL_STEPS OPD_STUDENT_ANCHOR_KL_COEF OPD_KL_COEF
   OPD_SAMPLED_TOKEN_CACHE_MISS_POLICY OPD_SAMPLED_TOKEN_CLIP_REFERENCE OPD_SAMPLED_TOKEN_EPS_CLIP OPD_SAMPLED_TOKEN_EPS_CLIP_HIGH
   OPD_SAMPLED_TOKEN_SDAR_GATE OPD_SDAR_GATE_BETA OPD_SDAR_GATE_SCALE
   OPD_LET_TOKEN_IDS OPD_ME_TOKEN_IDS
   OPD_TOKEN_ID_BRIDGE OPD_TEACHER_TEMPLATE_MODEL OPD_STUDENT_VALID_VOCAB_SIZE
   OPD_TEACHER_NATIVE_REASONING_PREFIX OPD_TEACHER_CANONICAL_TEMPLATE
   OPD_TEACHER_REASONING_EFFORT
   OPD_TEACHER_MASK_STUDENT_FORMAT_TOKENS
   OPD_TEACHER_NORMALIZE_STUDENT_TOOL_TEMPLATE OPD_TEACHER_MASK_STUDENT_PRE_TOOL_CONTENT
   OPD_TEACHER_MIN_ALIGNMENT_RATE
   OFFLINE_OPD_CONCURRENCY OFFLINE_OPD_SAVE_STUDENT_TOPK_LOGPROBS SGLANG_OUTPUT_TOP_LOGPROBS_B64 SGLANG_RETURN_ORIGINAL_LOGPROB
   OFFLINE_OPD_VALID_VOCAB_SIZE OFFLINE_OPD_TOPK_REQUEST_EXTRA
   SGLANG_TOP_LOGPROBS_ON_TOKEN_ID_POSITIONS
   SLIME_ROLLOUT_ENGINE_PORT_BASE
   ROLLOUT_BATCH_SIZE PREFERRED_ROLLOUT_BATCH_SIZE NUM_ROLLOUT NUM_STEPS_PER_ROLLOUT GLOBAL_BATCH_SIZE
   TRAIN_STEPS
   ROLLOUT_GPUS_PER_ENGINE SGLANG_SERVER_CONCURRENCY SGLANG_ATTN_BACKEND
   TOOL_CALL_PARSER REASONING_PARSER
   MAX_CONTEXT_LEN MAX_GEN_LEN MAX_TOKENS_PER_GPU LOG_PROBS_CHUNK_SIZE TP_SIZE PP_SIZE CP_SIZE EXPERT_MP_SIZE EXPERT_TP_SIZE
   DISTRIBUTED_TIMEOUT_MINUTES
   TEACHER_MODEL TEACHER_IP TEACHER_PORT TEACHER_TP TEACHER_DP TEACHER_GPUS TEACHER_MEM_FRACTION TEACHER_NNODES TEACHER_REPLICAS
   TEACHER_ATTN_BACKEND TEACHER_ATTENTION_MODE TEACHER_ATTN_DP TEACHER_LOGITS_CHUNK TEACHER_NCCL_PORT_BASE TEACHER_CHUNKED_PREFILL_SIZE TEACHER_MAX_PREFILL_TOKENS TEACHER_WATCHDOG_TIMEOUT TEACHER_WAIT_TIMEOUT_SEC TEACHER_PHASE2_WAIT_TIMEOUT_SEC SGLANG_UNBALANCED_MODEL_LOADING_TIMEOUT_S
   TEACHER_MAX_RUNNING_REQUESTS TEACHER_KV_CACHE_DTYPE TEACHER_DENSE_ATTN_KV_LEN_THRESHOLD TEACHER_MAX_KV_CHUNK_CAPACITY
   TEACHER_NSA_SPARSE_PREFILL_Q_CHUNK TEACHER_NSA_MQA_LOGITS_MAX_ROWS TEACHER_MOE_TOKEN_CHUNK_SIZE TEACHER_MODEL_LOADER_THREADS TEACHER_PREWARM_WEIGHTS TEACHER_PREWARM_CONCURRENCY
   TEACHER_CUDA_LAUNCH_BLOCKING
   TEACHER_LAUNCH_ATTEMPTS
   TEACHER_DSV4_TORCH_ROUTING
   SCORE_CONCURRENCY SCORE_FILE_CONCURRENCY SCORE_MAX_ATTEMPTS SCORE_SHARD_INDEX SCORE_NUM_SHARDS SKIP_SERVE RM_URL
   PHASE1_SHUFFLE PHASE1_SHUFFLE_SEED PHASE1_SHUFFLE_BALANCE_KEY PHASE1_SHUFFLED_DIR PHASE1_SHUFFLE_WAIT_TIMEOUT_SEC
   PHASE2_SAMPLES_PER_FILE PHASE2_BALANCE_MANIFESTS PHASE2_DYNAMIC_SHARDING PHASE2_SAMPLE_OUTPUT PHASE2_ROLLOUT_ID_FROM_FILENAME OFFLINE_OPD_TOKEN_TOPK_DIAGNOSTICS OFFLINE_OPD_DIAGNOSTIC_TOPK SCORE_COORD_DIR PHASE2_FINALIZE_WAIT_TIMEOUT_SEC
   OFFLINE_OPD_MANIFEST_LOAD_WORKERS OFFLINE_OPD_TOPK_OVERLAP OFFLINE_OPD_IMPORTANCE_DEBUG OFFLINE_OPD_POSTHOC_MASK_TOOL_FORMAT OFFLINE_OPD_POSTHOC_ANCHOR_PROTOCOL_TOKENS OFFLINE_OPD_ALLOW_SUPPORT_TOPK_TRUNCATION
   OFFLINE_OPD_BALANCE_DATA
   OFFLINE_OPD_POSTHOC_MASK_LET_ME_PROB OFFLINE_OPD_POSTHOC_MASK_LET_ME_SEED PREFETCH_ROLLOUT_DATA OFFLINE_OPD_RESUME OFFLINE_OPD_FINETUNE
   OFFLINE_OPD_OVERRIDE_OPT_PARAM_SCHEDULER
   OFFLINE_OPD_FULL_VERIFY
   OFFLINE_OPD_ALLOW_SAMPLE_SUBSET
   OFFLINE_OPD_ALLOW_EXTERNAL_SAMPLE_SYMLINKS
   USE_WANDB WANDB_API_KEY WANDB_TEAM WANDB_PROJECT WANDB_GROUP WANDB_MODE WANDB_RUN_ID WANDB_RESUME
   GITHUB_PROXY no_proxy NO_PROXY HTTP_PROXY HTTPS_PROXY http_proxy https_proxy
   RLE_SECRET_FILE RLE_ENV RLE_TOOL_TYPE RLE_API_KEY
   NCCL_SOCKET_IFNAME GLOO_SOCKET_IFNAME PYTORCH_CUDA_ALLOC_CONF FLASHINFER_USE_CUDA_NORM
   OFFLINE_OPD_CHUNK_ARTIFACT OFFLINE_OPD_CHUNK_MODE XVOCAB_ASSETS
   OFFLINE_OPD_TEACHER_DENSE_TOPK OPD_CHUNK_TIER OPD_NM_ROWS_SAMPLED_TOKEN
   RAY_agent_register_timeout_ms RAY_WORKER_JOIN_DELAY_SECS WAIT_WORKER_SECS
)
for name in "${FORWARDED_VARS[@]}"; do
   if [[ -v "${name}" ]]; then
      CMD+=(-x "${name}")
   fi
done
CMD+=("${SCRIPT_DIR}/_rank_dispatch.sh")

echo "offline OPD ${PHASE}: nodes=${NNODES}, loss=${OFFLINE_OPD_LOSS_TYPE}, topk=${OPD_ID_TOPK}, run=${OFFLINE_OPD_RUN_SCRIPT}"
if [[ "${PHASE}" == phase3 ]]; then
   echo "offline OPD phase3 data: epochs=${TRAIN_EPOCHS}, shuffle=${EPOCH_SHUFFLE}, dir=${SCORED_DIR}"
fi
if [[ "${BACKGROUND}" == "--bg" ]]; then
   LOG="${SCRIPT_DIR}/launch.${PHASE}.log"
   nohup "${CMD[@]}" >"${LOG}" 2>&1 &
   echo "background launcher pid=$!, log=${LOG}"
else
   exec "${CMD[@]}"
fi
