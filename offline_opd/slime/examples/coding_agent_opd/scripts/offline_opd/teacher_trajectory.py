@dataclass(frozen=True)
class TeacherTrajectory:
    input_ids: list[int]
    prompt_length: int
    scored_positions: np.ndarray
    # Response-relative Student positions represented by ``scored_positions``.
    # Usually this is exactly flatnonzero(loss_mask).  Native-reasoning-prefix
    # mode omits the Student-only ``\n<think>`` structural prefix at the start
    # of every assistant turn, so the two position grids are no longer equal.
    student_scored_positions: np.ndarray
    alignment_stats: dict[str, int | float]
    student_anchor_positions: np.ndarray | None = None
    student_anchor_reasons: np.ndarray | None = None
    # Every response-relative position the Teacher itself generates (the union of the
    # per-turn assistant deltas); ``scored_positions`` is its 1:1-with-Student subset.
    # Used by the Teacher-indexed dense dump.
    teacher_assistant_positions: np.ndarray | None = None


@lru_cache(maxsize=4)
def _load_tokenizer(model_path: str):
    return AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)


def _bridge_models(bridge: TokenIdBridge) -> tuple[str, str]:
    payload = json.loads(Path(bridge.path).read_text(encoding="utf-8"))
    student = payload.get("student_model")
    teacher = payload.get("teacher_model")
    if not isinstance(student, str) or not student:
        raise ValueError(f"{bridge.path}: token bridge has no student_model")
    if not isinstance(teacher, str) or not teacher:
        raise ValueError(f"{bridge.path}: token bridge has no teacher_model")
    return student, teacher


def _truncate_after_last_assistant(ids: list[int], tokenizer: Any, *, context: str) -> list[int]:
    """Drop template-injected generation content after the assistant role marker.

    GLM-5.2 appends ``<think>`` (and may append a reasoning-effort preamble) in its
    generation prompt.  Those bytes were not generated by the student and must not
    shift the distribution used to score the student's first token.  The role marker
    itself remains part of the prompt/connector, exactly as for GLM-4.5-Air.
    """
    assistant_id = tokenizer.convert_tokens_to_ids(_ASSISTANT_TOKEN)
    if assistant_id is None or assistant_id == tokenizer.unk_token_id:
        raise ValueError(f"{context}: tokenizer has no {_ASSISTANT_TOKEN!r} token")
    matches = [index for index, token_id in enumerate(ids) if token_id == assistant_id]
    if not matches:
        raise ValueError(f"{context}: rendered template has no {_ASSISTANT_TOKEN!r}")
    return ids[: matches[-1] + 1]


def _mask_runs(mask: np.ndarray) -> list[tuple[bool, int, int]]:
    if mask.size == 0:
        return []
    boundaries = np.flatnonzero(mask[1:] != mask[:-1]) + 1
    starts = np.r_[0, boundaries]
    ends = np.r_[boundaries, mask.size]
    return [(bool(mask[start]), int(start), int(end)) for start, end in zip(starts, ends)]


def _student_tool_call_policy(
    tokenizer: Any,
    scaffold,
    run_ids: list[int],
    *,
    normalize_tool_template: bool,
    mask_pre_tool_content: bool,
    context: str,
) -> tuple[set[int], set[int]]:
    """Return Student offsets to omit from Teacher context and from OPD loss.

    The GLM-4.5 tool grammar puts standalone newlines between its structural
    fields, while GLM-5.2 uses the same markers without those separators.  For
    a tool call that the Phase-1 parser accepts, omit only newlines outside an
    ``arg_value`` payload from the Teacher replay.  Newlines inside argument
    values are semantic command/code bytes and must remain untouched.

    Optionally exclude visible transition text between ``</think>`` and the
    final tool call from the loss.  That text stays in both model contexts so
    later token distributions are still conditioned on the trajectory that was
    actually sampled.

    Malformed/unparsed calls fail closed: no token is omitted or newly masked.
    """
    if not (normalize_tool_template or mask_pre_tool_content):
        return set(), set()

    marker_names = (
        "<|observation|>",
        "</think>",
        "<tool_call>",
        "</tool_call>",
        "<arg_value>",
        "</arg_value>",
    )
    marker_ids: dict[str, int] = {}
    for marker in marker_names:
        token_id = tokenizer.convert_tokens_to_ids(marker)
        if token_id is None or token_id == tokenizer.unk_token_id:
            raise ValueError(f"{context}: Student tokenizer has no {marker!r} token")
        marker_ids[marker] = int(token_id)
    newline_ids = tokenizer("\n", add_special_tokens=False)["input_ids"]
    if len(newline_ids) != 1:
        raise ValueError(
            f"{context}: Student newline must be one token, got {newline_ids!r}"
        )
    newline_id = int(newline_ids[0])

    assistant_ids = run_ids
    if assistant_ids and assistant_ids[-1] in {
        tokenizer.eos_token_id,
        marker_ids["<|observation|>"],
    }:
        assistant_ids = assistant_ids[:-1]
    assistant_text = tokenizer.decode(assistant_ids, skip_special_tokens=False)
    message = _canonical_assistant_message(
        assistant_text,
        scaffold,
        context=context,
    )
    if not message.get("tool_calls"):
        return set(), set()

    tool_start_id = marker_ids["<tool_call>"]
    tool_end_id = marker_ids["</tool_call>"]
    starts = [index for index, token_id in enumerate(assistant_ids) if token_id == tool_start_id]
    if not starts:
        return set(), set()
    tool_start = starts[-1]
    ends = [
        index
        for index in range(tool_start + 1, len(assistant_ids))
        if assistant_ids[index] == tool_end_id
    ]
    if len(ends) != 1:
        return set(), set()
    tool_end = ends[0]

    omit_from_teacher: set[int] = set()
    if normalize_tool_template:
        arg_value_start = marker_ids["<arg_value>"]
        arg_value_end = marker_ids["</arg_value>"]
        inside_arg_value = False
        for index in range(tool_start + 1, tool_end):
            token_id = assistant_ids[index]
            if token_id == arg_value_start:
                if inside_arg_value:
                    return set(), set()
                inside_arg_value = True
            elif token_id == arg_value_end:
                if not inside_arg_value:
                    return set(), set()
                inside_arg_value = False
            elif token_id == newline_id and not inside_arg_value:
                omit_from_teacher.add(index)
        if inside_arg_value:
            return set(), set()

    mask_from_loss = set(omit_from_teacher)
    if mask_pre_tool_content:
        think_end_id = marker_ids["</think>"]
        think_ends = [
            index
            for index in range(tool_start)
            if assistant_ids[index] == think_end_id
        ]
        if think_ends:
            mask_from_loss.update(range(think_ends[-1] + 1, tool_start))
    return omit_from_teacher, mask_from_loss


_POSTHOC_DYNAMIC_ROW_FIELDS = (
    "student_topk_ids",
    "student_topk_logprobs",
    "teacher_candidate_ids",
    "teacher_candidate_logprobs",
    "teacher_top128_ids",
    "teacher_cutoff_logprobs",
    "teacher_top4096_mass",
)


def _select_sparse_rows(value: Any, keep_rows: np.ndarray, *, field: str, context: str):
    """Select rows without changing a scored artifact's tensor/array type."""
    if value is None:
        raise ValueError(f"{context}: post-hoc remask requires {field}")
    if len(value) != len(keep_rows):
        raise ValueError(
            f"{context}: {field} rows={len(value)} do not match old trainable "
            f"rows={len(keep_rows)}"
        )
    if isinstance(value, np.ndarray):
        return np.ascontiguousarray(value[keep_rows])

    import torch

    if isinstance(value, torch.Tensor):
        index = torch.from_numpy(np.flatnonzero(keep_rows)).to(value.device)
        return value.index_select(0, index).contiguous()
    raise TypeError(f"{context}: unsupported {field} type {type(value).__name__}")


def posthoc_anchor_protocol_tokens_dynamic_scored_sample(
    sample: Sample,
    student_tokenizer: Any,
    *,
    cache_topk: int,
    dynamic_topk: int,
    context: str = "offline post-hoc protocol anchor",
) -> dict[str, int]:
    """Move protocol-critical Teacher rows to the rollout-Student anchor.

    Canonical cross-tokenizer artifacts retain the rollout Student Top-K on
    every exact Teacher row. Selected rows can therefore be repartitioned into
    the Student anchor without another Teacher forward. Special tokens are
    intentionally identified globally by token id; ordinary reasoning, tool
    names, argument names, and argument values remain Teacher-supervised.
    """
    import torch

    from examples.coding_agent_opd.scripts.offline_opd.offline_utils import (
        validate_cross_tokenizer_anchor_scored_sample,
    )

    validate_cross_tokenizer_anchor_scored_sample(
        sample,
        cache_topk=cache_topk,
        dynamic_topk=dynamic_topk,
        context=f"{context}: input",
    )
    if len(sample.tokens) < sample.response_length:
        raise ValueError(f"{context}: response exceeds complete token sequence")

    response_ids = np.asarray(
        sample.tokens[-sample.response_length :], dtype=np.int64
    )
    trainable_mask = np.asarray(sample.loss_mask, dtype=bool)
    teacher_positions = np.asarray(
        sample.teacher_candidate_positions, dtype=np.int32
    )
    old_anchor_positions = np.asarray(
        sample.student_anchor_positions, dtype=np.int32
    )

    marker_reason = {
        "<think>": 1,
        "</think>": 5,
        "<tool_call>": 7,
        "</tool_call>": 7,
        "<arg_key>": 7,
        "</arg_key>": 7,
        "<arg_value>": 7,
        "</arg_value>": 7,
        "<|observation|>": 3,
    }
    if _align_protocol_pairs_enabled():
        # With a protocol-pair bridge these rows are Teacher-supervised (Phase 2 aligns
        # them iff the bridge maps them); re-anchoring them would undo that.
        for marker in _PROTOCOL_STUDENT_TOKENS:
            marker_reason.pop(marker, None)
    marker_ids: dict[str, int] = {}
    for marker in marker_reason:
        token_id = student_tokenizer.convert_tokens_to_ids(marker)
        if token_id is None or token_id == student_tokenizer.unk_token_id:
            raise ValueError(f"{context}: Student tokenizer has no {marker!r} token")
        marker_ids[marker] = int(token_id)

    reason_by_position: dict[int, int] = {}

    def first_trainable_after(position: int) -> int | None:
        for following in range(position + 1, sample.response_length):
            if trainable_mask[following]:
                return following
        return None

    # Guard only the first trainable predicted token after each reasoning
    # delimiter, skipping any already-masked template rows. A marker at the
    # same position receives its more specific reason below.
    for position in np.flatnonzero(response_ids == marker_ids["<think>"]):
        following = first_trainable_after(int(position))
        if following is not None:
            reason_by_position[following] = 4
    for position in np.flatnonzero(response_ids == marker_ids["</think>"]):
        following = first_trainable_after(int(position))
        if following is not None:
            reason_by_position[following] = 6

    for marker, reason in marker_reason.items():
        for position in np.flatnonzero(response_ids == marker_ids[marker]):
            if trainable_mask[position]:
                reason_by_position[int(position)] = reason

    # Current GLM rollouts do not train EOS, but protect it if a later rollout
    # format retains a terminal generation token in the response loss mask.
    stop_ids: set[int] = set()
    eos_id = getattr(student_tokenizer, "eos_token_id", None)
    if eos_id is not None and int(eos_id) >= 0:
        stop_ids.add(int(eos_id))
    end_id = student_tokenizer.convert_tokens_to_ids("<|endoftext|>")
    if end_id is not None and end_id != student_tokenizer.unk_token_id:
        stop_ids.add(int(end_id))
    for stop_id in stop_ids:
        for position in np.flatnonzero(response_ids == stop_id):
            if trainable_mask[position]:
                reason_by_position[int(position)] = 8

    selected_positions = np.asarray(sorted(reason_by_position), dtype=np.int32)
    move_rows = np.isin(teacher_positions, selected_positions)
    keep_rows = ~move_rows
    moved_positions = teacher_positions[move_rows]
    moved_reasons = np.asarray(
        [reason_by_position[int(position)] for position in moved_positions],
        dtype=np.int8,
    )

    def cpu_numpy(value: Any) -> np.ndarray:
        if isinstance(value, torch.Tensor):
            return value.detach().cpu().numpy()
        return np.asarray(value)

    teacher_student_ids = cpu_numpy(sample.student_topk_ids)
    teacher_student_lp = cpu_numpy(sample.student_topk_logprobs)
    moved_ids = np.ascontiguousarray(teacher_student_ids[move_rows], dtype=np.int32)
    moved_lp = np.ascontiguousarray(teacher_student_lp[move_rows], dtype=np.float16)

    old_anchor_ids = cpu_numpy(sample.student_anchor_topk_ids)
    old_anchor_lp = cpu_numpy(sample.student_anchor_topk_logprobs)
    old_anchor_reasons = cpu_numpy(sample.student_anchor_reason)
    merged_positions = np.concatenate((old_anchor_positions, moved_positions))
    merged_ids = np.concatenate((old_anchor_ids, moved_ids), axis=0)
    merged_lp = np.concatenate((old_anchor_lp, moved_lp), axis=0)
    merged_reasons = np.concatenate((old_anchor_reasons, moved_reasons))
    order = np.argsort(merged_positions, kind="stable")
    merged_positions = np.ascontiguousarray(merged_positions[order], dtype=np.int32)
    merged_ids = np.ascontiguousarray(merged_ids[order], dtype=np.int32)
    merged_lp = np.ascontiguousarray(merged_lp[order], dtype=np.float16)
    merged_reasons = np.ascontiguousarray(merged_reasons[order], dtype=np.int8)

    for field in _POSTHOC_DYNAMIC_ROW_FIELDS:
        setattr(
            sample,
            field,
            _select_sparse_rows(
                getattr(sample, field), keep_rows, field=field, context=context
            ),
        )
    sample.teacher_candidate_positions = torch.from_numpy(
        np.ascontiguousarray(teacher_positions[keep_rows], dtype=np.int32)
    )
    sample.student_anchor_positions = torch.from_numpy(merged_positions)
    sample.student_anchor_topk_ids = torch.from_numpy(merged_ids)
    sample.student_anchor_topk_logprobs = torch.from_numpy(merged_lp)
    sample.student_anchor_reason = torch.from_numpy(merged_reasons)

    moved_reason_counts = {
        reason: int(np.count_nonzero(moved_reasons == reason))
        for reason in (4, 5, 6, 7, 8)
    }
    sample.metadata = dict(sample.metadata or {})
    sample.metadata.update(
        {
            "offline_opd_posthoc_anchor_protocol_tokens": True,
            "offline_opd_posthoc_anchor_protocol_policy": "global_special_v1",
            "offline_opd_posthoc_anchor_old_teacher_rows": int(teacher_positions.size),
            "offline_opd_posthoc_anchor_old_anchor_rows": int(old_anchor_positions.size),
            "offline_opd_posthoc_anchor_selected_positions": int(selected_positions.size),
            "offline_opd_posthoc_anchor_moved_rows": int(moved_positions.size),
            "offline_opd_posthoc_anchor_new_teacher_rows": int(keep_rows.sum()),
            "offline_opd_posthoc_anchor_new_anchor_rows": int(merged_positions.size),
            "offline_opd_posthoc_anchor_reasoning_first_token_rows": moved_reason_counts[4],
            "offline_opd_posthoc_anchor_reasoning_end_rows": moved_reason_counts[5],
            "offline_opd_posthoc_anchor_post_reasoning_transition_rows": moved_reason_counts[6],
            "offline_opd_posthoc_anchor_tool_protocol_rows": moved_reason_counts[7],
            "offline_opd_posthoc_anchor_stop_token_rows": moved_reason_counts[8],
        }
    )
    validate_cross_tokenizer_anchor_scored_sample(
        sample,
        cache_topk=cache_topk,
        dynamic_topk=dynamic_topk,
        context=f"{context}: output",
    )
    return {
        "old_teacher_rows": int(teacher_positions.size),
        "old_anchor_rows": int(old_anchor_positions.size),
        "selected_positions": int(selected_positions.size),
        "moved_rows": int(moved_positions.size),
        "new_teacher_rows": int(keep_rows.sum()),
        "new_anchor_rows": int(merged_positions.size),
        "reasoning_first_token_rows": moved_reason_counts[4],
        "reasoning_end_rows": moved_reason_counts[5],
        "post_reasoning_transition_rows": moved_reason_counts[6],
        "tool_protocol_rows": moved_reason_counts[7],
        "stop_token_rows": moved_reason_counts[8],
    }


def posthoc_mask_dynamic_scored_sample(
    sample: Sample,
    student_tokenizer: Any,
    scaffold,
    *,
    cache_topk: int,
    dynamic_topk: int,
    context: str = "offline post-hoc remask",
) -> dict[str, int]:
    """Mask GLM tool-format artifacts in an already-scored dynamic sample.

    This is intentionally a Phase-3-only ablation path.  It does not rewrite
    the response or pretend that cached Teacher logits were produced under a
    different context.  It only removes selected response positions from the
    loss and compacts every sparse row-aligned tensor by the exact same mask.

    Real assistant turns are delimited by the scaffold connectors emitted by
    Phase 1: the first starts at response offset zero; later turns start after
    ``</tool_response><|assistant|>``; valid executed calls end immediately
    before ``<|observation|>``.  The existing Phase-2 parser remains the source
    of truth and fails closed for malformed calls.
    """
    import torch

    if not sample.offline_opd_dynamic_teacher_sparse:
        raise ValueError(f"{context}: sample is not a dynamic sparse Teacher artifact")
    if sample.loss_mask is None or len(sample.loss_mask) != sample.response_length:
        raise ValueError(f"{context}: invalid response-aligned loss_mask")
    if len(sample.tokens) < sample.response_length:
        raise ValueError(f"{context}: response exceeds complete token sequence")

    response_ids = list(sample.tokens[-sample.response_length :])
    old_mask = np.asarray(sample.loss_mask, dtype=bool)
    old_positions = np.flatnonzero(old_mask).astype(np.int32)
    stored_positions = np.asarray(sample.teacher_candidate_positions, dtype=np.int32)
    if not np.array_equal(stored_positions, old_positions):
        raise ValueError(f"{context}: existing candidate positions do not match loss_mask")

    marker_names = (
        "<|assistant|>",
        "<|observation|>",
        "</tool_call>",
        "</tool_response>",
    )
    marker_ids: dict[str, int] = {}
    for marker in marker_names:
        token_id = student_tokenizer.convert_tokens_to_ids(marker)
        if token_id is None or token_id == student_tokenizer.unk_token_id:
            raise ValueError(f"{context}: Student tokenizer has no {marker!r} token")
        marker_ids[marker] = int(token_id)

    assistant_starts = [0]
    assistant_id = marker_ids["<|assistant|>"]
    tool_response_end_id = marker_ids["</tool_response>"]
    assistant_starts.extend(
        index + 1
        for index, token_id in enumerate(response_ids)
        if token_id == assistant_id
        and index > 0
        and response_ids[index - 1] == tool_response_end_id
    )
    observation_id = marker_ids["<|observation|>"]
    tool_end_id = marker_ids["</tool_call>"]
    observation_ends = [
        index + 1
        for index, token_id in enumerate(response_ids)
        if token_id == observation_id
        and index > 0
        and response_ids[index - 1] == tool_end_id
    ]

    drop_positions: set[int] = set()
    observation_cursor = 0
    parsed_turns = 0
    for start in assistant_starts:
        while observation_cursor < len(observation_ends) and observation_ends[observation_cursor] <= start:
            observation_cursor += 1
        if observation_cursor >= len(observation_ends):
            # A terminal plain-text assistant turn has no tool call and therefore
            # contains neither category targeted by this ablation.
            break
        end = observation_ends[observation_cursor]
        observation_cursor += 1
        _, masked_offsets = _student_tool_call_policy(
            student_tokenizer,
            scaffold,
            response_ids[start:end],
            normalize_tool_template=True,
            mask_pre_tool_content=True,
            context=f"{context}: assistant turn {parsed_turns}",
        )
        drop_positions.update(start + offset for offset in masked_offsets)
        parsed_turns += 1

    # Already-masked format markers are harmless.  Only old sparse rows need to
    # be removed, and deriving keep_rows from old_positions preserves the exact
    # row-to-response mapping used by Phase 2.
    removed_positions = np.asarray(
        sorted(position for position in drop_positions if old_mask[position]),
        dtype=np.int32,
    )
    keep_rows = ~np.isin(old_positions, removed_positions)
    new_positions = old_positions[keep_rows]
    new_mask = np.zeros(sample.response_length, dtype=np.int8)
    new_mask[new_positions] = 1

    for field in _POSTHOC_DYNAMIC_ROW_FIELDS:
        setattr(
            sample,
            field,
            _select_sparse_rows(
                getattr(sample, field), keep_rows, field=field, context=context
            ),
        )
    sample.teacher_candidate_positions = torch.from_numpy(new_positions.copy())
    sample.loss_mask = new_mask.tolist()
    sample.metadata = dict(sample.metadata or {})
    sample.metadata.update(
        {
            "offline_opd_posthoc_mask_tool_format": True,
            "offline_opd_posthoc_old_trainable_tokens": int(len(old_positions)),
            "offline_opd_posthoc_removed_trainable_tokens": int(len(removed_positions)),
            "offline_opd_posthoc_trainable_tokens": int(len(new_positions)),
            "offline_opd_posthoc_parsed_assistant_turns": parsed_turns,
        }
    )

    from examples.coding_agent_opd.scripts.offline_opd.offline_utils import (
        validate_dynamic_scored_sample,
    )

    validate_dynamic_scored_sample(
        sample,
        cache_topk=cache_topk,
        dynamic_topk=dynamic_topk,
        context=context,
    )
    return {
        "old_trainable_tokens": int(len(old_positions)),
        "removed_trainable_tokens": int(len(removed_positions)),
        "trainable_tokens": int(len(new_positions)),
        "parsed_assistant_turns": parsed_turns,
    }


def posthoc_mask_let_me_triplets_dynamic_scored_sample(
    sample: Sample,
    *,
    let_token_ids: set[int],
    me_token_ids: set[int],
    probability: float,
    seed: int,
    cache_topk: int,
    dynamic_topk: int,
    context: str = "offline post-hoc Let-me mask",
) -> dict[str, int]:
    """Deterministically mask sampled ``Let/let + me + X`` token triples.

    The decision is keyed by ``(seed, sample.index, response_position)`` rather
    than process RNG state.  Repeated loading, epoch fanout, worker-count
    changes, and DP reshuffling therefore select exactly the same occurrences.
    Only triples whose three positions are already trainable are eligible.  The
    original artifact is not modified on disk; all row-aligned sparse Student
    and Teacher tensors are compacted on the loaded ``Sample`` together.
    """
    import torch

    if not 0.0 <= probability <= 1.0:
        raise ValueError(f"{context}: probability must be in [0, 1], got {probability}")
    if not sample.offline_opd_dynamic_teacher_sparse:
        raise ValueError(f"{context}: sample is not a dynamic sparse Teacher artifact")
    if sample.loss_mask is None or len(sample.loss_mask) != sample.response_length:
        raise ValueError(f"{context}: invalid response-aligned loss_mask")
    if len(sample.tokens) < sample.response_length:
        raise ValueError(f"{context}: response exceeds complete token sequence")

    response_ids = np.asarray(sample.tokens[-sample.response_length :], dtype=np.int64)
    old_mask = np.asarray(sample.loss_mask, dtype=bool)
    old_positions = np.flatnonzero(old_mask).astype(np.int32)
    stored_positions = np.asarray(sample.teacher_candidate_positions, dtype=np.int32)
    if not np.array_equal(stored_positions, old_positions):
        raise ValueError(f"{context}: existing candidate positions do not match loss_mask")

    occurrences = 0
    selected_occurrences = 0
    drop_positions: set[int] = set()
    threshold = int(probability * (1 << 64))
    sample_index = int(sample.index)
    for start in range(max(len(response_ids) - 2, 0)):
        if (
            int(response_ids[start]) not in let_token_ids
            or int(response_ids[start + 1]) not in me_token_ids
            or not bool(old_mask[start : start + 3].all())
        ):
            continue
        occurrences += 1
        key = f"{seed}:{sample_index}:{start}".encode("utf-8")
        draw = int.from_bytes(
            hashlib.blake2b(key, digest_size=8, person=b"slime-let-me").digest(),
            "big",
        )
        if draw < threshold:
            selected_occurrences += 1
            drop_positions.update((start, start + 1, start + 2))

    removed_positions = np.asarray(sorted(drop_positions), dtype=np.int32)
    keep_rows = ~np.isin(old_positions, removed_positions)
    new_positions = old_positions[keep_rows]
    new_mask = np.zeros(sample.response_length, dtype=np.int8)
    new_mask[new_positions] = 1

    for field in _POSTHOC_DYNAMIC_ROW_FIELDS:
        setattr(
            sample,
            field,
            _select_sparse_rows(
                getattr(sample, field), keep_rows, field=field, context=context
            ),
        )
    sample.teacher_candidate_positions = torch.from_numpy(new_positions.copy())
    sample.loss_mask = new_mask.tolist()
    sample.metadata = dict(sample.metadata or {})
    sample.metadata.update(
        {
            "offline_opd_posthoc_mask_let_me_probability": float(probability),
            "offline_opd_posthoc_mask_let_me_seed": int(seed),
            "offline_opd_posthoc_mask_let_me_occurrences": occurrences,
            "offline_opd_posthoc_mask_let_me_selected_occurrences": selected_occurrences,
            "offline_opd_posthoc_mask_let_me_removed_trainable_tokens": int(
                len(removed_positions)
            ),
            "offline_opd_posthoc_mask_let_me_trainable_tokens": int(len(new_positions)),
        }
    )

    from examples.coding_agent_opd.scripts.offline_opd.offline_utils import (
        validate_dynamic_scored_sample,
    )

    validate_dynamic_scored_sample(
        sample,
        cache_topk=cache_topk,
        dynamic_topk=dynamic_topk,
        context=context,
    )
    return {
        "old_trainable_tokens": int(len(old_positions)),
        "occurrences": occurrences,
        "selected_occurrences": selected_occurrences,
        "removed_trainable_tokens": int(len(removed_positions)),
        "trainable_tokens": int(len(new_positions)),
    }


def _render_template(
    tokenizer: Any,
    messages: list[dict],
    *,
    tools,
    add_generation_prompt: bool,
    reasoning_effort: str | None = None,
) -> tuple[list[int], str]:
    template_kwargs = {}
    if reasoning_effort is not None:
        template_kwargs["reasoning_effort"] = reasoning_effort
    text = tokenizer.apply_chat_template(
        messages,
        tools=tools,
        tokenize=False,
        add_generation_prompt=add_generation_prompt,
        **template_kwargs,
    )
    ids = tokenizer(text, add_special_tokens=False)["input_ids"]
    return list(ids), text


def _canonical_assistant_message(
    assistant_text: str,
    scaffold,
    *,
    context: str,
) -> dict:
    """Parse one GLM-4.5 assistant turn into GLM-5.2 template fields."""
    prefix = "\n<think>"
    close = "</think>"
    has_reasoning_prefix = assistant_text.startswith(prefix)
    reasoning_start = len(prefix) if has_reasoning_prefix else 0
    close_at = assistant_text.find(close, reasoning_start)
    if close_at < 0:
        if not has_reasoning_prefix:
            # A turn without either reasoning delimiter is ordinary visible
            # assistant content.  The complete Phase-1 parser below remains the
            # authority on whether its final raw tool call was actually executed.
            reasoning = ""
            remainder = assistant_text
        else:
            # Some sampled turns misspell/omit the reasoning terminator but still
            # contain a valid final tool call that Phase 1 executed.  Preserve the
            # unterminated prefix as reasoning and let the Teacher's official
            # template insert its own closing </think>; the final raw call remains
            # available for the same structured-parser verification below.  A turn
            # with no call is simply an all-reasoning assistant message.
            raw_tool_at = assistant_text.rfind("<tool_call>")
            if raw_tool_at < reasoning_start:
                reasoning = assistant_text[reasoning_start:]
                remainder = ""
            else:
                reasoning = assistant_text[reasoning_start:raw_tool_at]
                remainder = assistant_text[raw_tool_at:]
    else:
        # Rarely a later sampled turn omits the opening <think> while still
        # emitting </think>.  Interpret the bytes preceding the close marker as
        # reasoning so the Teacher receives the same semantic fields through its
        # own complete canonical template.
        reasoning = assistant_text[reasoning_start:close_at]
        remainder = assistant_text[close_at + len(close) :]

    message: dict[str, Any] = {
        "role": "assistant",
        "reasoning_content": reasoning,
        "content": remainder,
    }
    tool_at = remainder.rfind("<tool_call>")
    if tool_at < 0:
        return message

    from examples.coding_agent_opd.r2egym import action as agent_action

    parser_kwargs = {
        "tool_call_parser": os.environ.get("TOOL_CALL_PARSER", "glm45") or "glm45",
        "reasoning_parser": os.environ.get("REASONING_PARSER", "glm45") or "glm45",
    }
    _, action = agent_action.parse(
        assistant_text,
        scaffold,
        **parser_kwargs,
    )
    # Preserve the Phase-1 environment's decision.  A malformed generation may
    # contain text that *looks* like a nested/partial tool call while the rollout
    # parser rejected the complete assistant message.  In that case the following
    # observation is the parser-error observation, not the result of the innermost
    # syntactically valid call.  Treat all markup as ordinary assistant content in
    # the Teacher template instead of inventing a tool execution that never happened.
    if action is None:
        return message

    if not remainder.rstrip().endswith("</tool_call>"):
        # The rollout parser may recover an executable call from a malformed
        # payload that still has trailing markup/text.  It is unsafe to render
        # that recovered call through the Teacher template because doing so
        # would silently discard the trailing bytes.  Fail closed in the same
        # way as an unparsed/nested call: retain the complete Student payload as
        # ordinary assistant content and do not normalize/mask its structure.
        return message
    # The structured call must also be the final raw call.  This catches a complete
    # message whose parser selected an earlier call while a later malformed call is
    # present; representing the later span with the earlier action would silently
    # alter both context semantics and Student/Teacher token alignment.
    _, final_action = agent_action.parse(remainder[tool_at:], scaffold, **parser_kwargs)
    if (
        final_action is None
        or final_action.function_name != action.function_name
        or final_action.parameters != action.parameters
    ):
        return message

    message["content"] = remainder[:tool_at]
    message["tool_calls"] = [
        {
            "type": "function",
            "function": {
                "name": action.function_name,
                "arguments": action.parameters,
            },
        }
    ]
    return message


def _template_turn_deltas(
    teacher_tokenizer: Any,
    assistant_message: dict,
    observation_message: dict | None,
    *,
    context: str,
    reasoning_effort: str | None = None,
) -> tuple[list[int], str, list[int], str, int]:
    """Render canonical assistant/connector deltas in a bounded probe history.

    The trailing element is the number of tokens the caller must drop from the
    already-assembled generation prompt before appending the assistant delta.
    """
    probe = [{"role": "user", "content": "SLIME_TEMPLATE_ALIGNMENT_PROBE"}]
    base_ids, base_text = _render_template(
        teacher_tokenizer,
        probe,
        tools=None,
        add_generation_prompt=True,
        reasoning_effort=reasoning_effort,
    )
    assistant_ids, assistant_text = _render_template(
        teacher_tokenizer,
        probe + [assistant_message],
        tools=None,
        add_generation_prompt=False,
        reasoning_effort=reasoning_effort,
    )
    prompt_drop = 0
    if assistant_ids[: len(base_ids)] != base_ids or not assistant_text.startswith(base_text):
        # A blank reasoning block renders "<|im_start|>assistant\n</think>" while the
        # generation prompt ends "...assistant\n<think>": a legal GLM-4.5 turn that
        # swaps the prompt's opening <think> for the closing one. Re-anchor the delta
        # on the prompt minus that token and report it so the caller drops it; the
        # final full-history render still checks the result against the template.
        open_think = "<think>"
        stem_ids = base_ids[:-1]
        stem_text = base_text[: -len(open_think)] if base_text.endswith(open_think) else ""
        if (
            not stem_text
            or teacher_tokenizer.decode(base_ids[-1:], skip_special_tokens=False) != open_think
            or assistant_ids[: len(stem_ids)] != stem_ids
            or not assistant_text.startswith(stem_text)
        ):
            raise ValueError(
                f"{context}: canonical assistant render is not generation-prompt prefixed"
            )
        prompt_drop = 1
        base_ids, base_text = stem_ids, stem_text
    assistant_delta_ids = assistant_ids[len(base_ids) :]
    assistant_delta_text = assistant_text[len(base_text) :]

    if observation_message is None:
        return assistant_delta_ids, assistant_delta_text, [], "", prompt_drop
    full_ids, full_text = _render_template(
        teacher_tokenizer,
        probe + [assistant_message, observation_message],
        tools=None,
        add_generation_prompt=True,
        reasoning_effort=reasoning_effort,
    )
    if full_ids[: len(assistant_ids)] != assistant_ids or not full_text.startswith(
        assistant_text
    ):
        raise ValueError(f"{context}: canonical observation render is not assistant-prefixed")
    return (
        assistant_delta_ids,
        assistant_delta_text,
        full_ids[len(assistant_ids) :],
        full_text[len(assistant_text) :],
        prompt_drop,
    )


def _encode_with_offsets(
    tokenizer: Any,
    text: str,
    expected_ids: list[int],
    *,
    context: str,
) -> list[tuple[int, int]]:
    encoded = tokenizer(
        text,
        add_special_tokens=False,
        return_offsets_mapping=True,
    )
    ids = list(encoded["input_ids"])
    if ids != expected_ids:
        raise ValueError(f"{context}: decoded text does not round-trip to the stored token ids")
    offsets = [(int(start), int(end)) for start, end in encoded["offset_mapping"]]
    if len(offsets) != len(ids):
        raise ValueError(f"{context}: tokenizer returned an invalid offset mapping")
    return offsets


def _canonical_student_offsets(
    tokenizer: Any,
    text: str,
    stored_ids: list[int],
) -> tuple[list[int], list[tuple[int, int]], dict[int, int]]:
    """Offsets for arbitrary sampled ids via their canonical re-encoding.

    A model may emit a valid but non-canonical token sequence (for example two
    old tokens where the tokenizer encoder now selects one merged token). Such
    stored positions intentionally receive no offset and are therefore masked.
    """
    encoded = tokenizer(
        text,
        add_special_tokens=False,
        return_offsets_mapping=True,
    )
    canonical_ids = list(encoded["input_ids"])
    offsets = [(int(start), int(end)) for start, end in encoded["offset_mapping"]]
    if len(offsets) != len(canonical_ids):
        raise ValueError("Student tokenizer returned an invalid offset mapping")
    stored_to_canonical: dict[int, int] = {}
    matcher = SequenceMatcher(None, stored_ids, canonical_ids, autojunk=False)
    for stored_start, canonical_start, size in matcher.get_matching_blocks():
        for delta in range(size):
            stored_to_canonical[stored_start + delta] = canonical_start + delta
    return canonical_ids, offsets, stored_to_canonical


def _align_canonical_turn(
    student_tokenizer: Any,
    teacher_tokenizer: Any,
    bridge: TokenIdBridge,
    student_ids: list[int],
    teacher_ids: list[int],
    teacher_text: str,
    *,
    context: str,
) -> list[tuple[int, int]]:
    """One-to-one token alignment inside exact equal-text regions only."""
    student_text = student_tokenizer.decode(student_ids, skip_special_tokens=False)
    _, canonical_student_offsets, stored_to_canonical = _canonical_student_offsets(
        student_tokenizer, student_text, student_ids
    )
    teacher_offsets = _encode_with_offsets(
        teacher_tokenizer,
        teacher_text,
        teacher_ids,
        context=f"{context}: Teacher",
    )
    teacher_by_span: dict[tuple[int, int], list[int]] = {}
    for index, span in enumerate(teacher_offsets):
        if span[1] > span[0]:
            teacher_by_span.setdefault(span, []).append(index)

    # The mapped id is only compared against one candidate teacher id, so an unmapped
    # Student token (-1) needs no special case: it never matches and ends up a Student
    # anchor. A strict mapping would fail a different teacher vocabulary outright.
    mapped_student_ids = bridge.map_numpy(
        np.asarray(student_ids, dtype=np.int32),
        context=f"{context}: Student ids",
        allow_unmapped=True,
    )
    aligned: list[tuple[int, int]] = []
    used_teacher: set[int] = set()
    matcher = SequenceMatcher(None, student_text, teacher_text, autojunk=False)
    for student_char, teacher_char, size in matcher.get_matching_blocks():
        if size <= 0:
            continue
        student_stop = student_char + size
        for student_index, canonical_index in stored_to_canonical.items():
            start, end = canonical_student_offsets[canonical_index]
            if start < student_char or end > student_stop or end <= start:
                continue
            teacher_span = (
                teacher_char + start - student_char,
                teacher_char + end - student_char,
            )
            candidates = teacher_by_span.get(teacher_span, ())
            if len(candidates) != 1:
                continue
            teacher_index = candidates[0]
            if teacher_index in used_teacher:
                continue
            if int(mapped_student_ids[student_index]) != int(teacher_ids[teacher_index]):
                continue
            if student_text[start:end].encode("utf-8") != teacher_text[
                teacher_span[0] : teacher_span[1]
            ].encode("utf-8"):
                continue
            aligned.append((student_index, teacher_index))
            used_teacher.add(teacher_index)
    aligned.sort()
    if _bridge_has_protocol_pairs(student_tokenizer, bridge):
        aligned = _add_protocol_pairs(
            student_tokenizer, bridge, student_ids, teacher_ids, aligned
        )
    if any(
        left[0] >= right[0] or left[1] >= right[1]
        for left, right in zip(aligned, aligned[1:])
    ):
        raise ValueError(f"{context}: canonical token alignment is not strictly monotonic")
    return aligned


# Student protocol tokens that are paired with their Teacher functional counterpart
# by id (the bridge's PROTOCOL_PAIRS), even though the decoded text differs.
_PROTOCOL_STUDENT_TOKENS = ("<tool_call>", "</tool_call>", "<|observation|>")


def _bridge_has_protocol_pairs(student_tokenizer: Any, bridge: TokenIdBridge) -> bool:
    """Phase-2 gate: protocol pairing is on iff the bridge itself maps them.

    Tying it to the bridge (whose sha256 Phase 3 checks against every scored
    artifact) makes the scored data and the runtime bridge agree by construction;
    an env flag forgotten on one mpirun rank cannot silently produce mixed data.
    """
    student_id = student_tokenizer.convert_tokens_to_ids("<tool_call>")
    if student_id is None or student_id == student_tokenizer.unk_token_id:
        return False
    return int(bridge.student_to_teacher[int(student_id)]) >= 0


def _align_protocol_pairs_enabled() -> bool:
    value = os.environ.get("OFFLINE_OPD_ALIGN_PROTOCOL_PAIRS", "0")
    if value not in {"0", "1"}:
        raise ValueError(f"OFFLINE_OPD_ALIGN_PROTOCOL_PAIRS must be 0 or 1, got {value!r}")
    return value == "1"


@lru_cache(maxsize=8)
def _protocol_pair_policies(bridge_path: str) -> dict[int, str]:
    """student id -> alignment policy, from the bridge JSON's protocol_pairs.

    Entries are [student_tok, student_id, teacher_tok, teacher_id(, policy)]; a
    missing policy is "auto" (the 10-16 SFT bridge has none).
    """
    try:
        payload = json.loads(Path(bridge_path).read_text())
    except (OSError, ValueError):
        return {}
    policies: dict[int, str] = {}
    for entry in payload.get("protocol_pairs") or ():
        policy = entry[4] if len(entry) > 4 else "auto"
        if policy not in {"auto", "student_last_teacher_first"}:
            raise ValueError(f"{bridge_path}: unknown protocol pair policy {policy!r}")
        policies[int(entry[1])] = policy
    return policies


def _add_protocol_pairs(
    student_tokenizer: Any,
    bridge: TokenIdBridge,
    student_ids: list[int],
    teacher_ids: list[int],
    aligned: list[tuple[int, int]],
) -> list[tuple[int, int]]:
    """Pair protocol tokens whose text differs but whose ids the bridge maps.

    The text-equality matcher can never align <tool_call> with <ernie:tool_call>,
    so those rows fell into the Student anchor and the Teacher's decision
    distribution at "start a tool call / end the turn" was never cached. With a
    bridge built by ``build_token_id_bridge.py --protocol-pairs`` the ids map
    1:1; pair occurrences in order when the counts agree, otherwise only the
    first (opening decision) and the last (closing decision) occurrence --
    GLM may emit several <tool_call> blocks where DSV4 wraps every invoke in one
    <ernie:tool_call>. A pair is inserted only where it keeps the alignment
    strictly monotonic in both sequences, so existing text pairs never move.
    """
    used_student = {pair[0] for pair in aligned}
    used_teacher = {pair[1] for pair in aligned}
    candidates: list[tuple[int, int]] = []
    student_array = np.asarray(student_ids, dtype=np.int64)
    teacher_array = np.asarray(teacher_ids, dtype=np.int64)
    for token in _PROTOCOL_STUDENT_TOKENS:
        student_id = student_tokenizer.convert_tokens_to_ids(token)
        if student_id is None or student_id == student_tokenizer.unk_token_id:
            continue
        teacher_id = int(bridge.student_to_teacher[int(student_id)])
        if teacher_id < 0:
            continue
        student_positions = np.flatnonzero(student_array == int(student_id)).tolist()
        teacher_positions = np.flatnonzero(teacher_array == teacher_id).tolist()
        if not student_positions or not teacher_positions:
            continue
        policy = _protocol_pair_policies(bridge.path).get(int(student_id), "auto")
        if policy == "student_last_teacher_first":
            # DSV4-0731: the |DSML| id recurs inside the tool_calls block, so only the
            # opener is "start a tool call". Student side: the parser keeps the LAST
            # <tool_call> as the action; earlier ones render as plain text.
            candidates.append((student_positions[-1], teacher_positions[0]))
        elif len(student_positions) == len(teacher_positions):
            candidates.extend(zip(student_positions, teacher_positions))
        else:
            candidates.append((student_positions[0], teacher_positions[0]))
            if len(student_positions) > 1 and len(teacher_positions) > 1:
                candidates.append((student_positions[-1], teacher_positions[-1]))
    result = list(aligned)
    for student_index, teacher_index in sorted(set(candidates)):
        if student_index in used_student or teacher_index in used_teacher:
            continue
        insert_at = bisect.bisect_left(result, (student_index, teacher_index))
        if insert_at > 0 and result[insert_at - 1][1] >= teacher_index:
            continue
        if insert_at < len(result) and result[insert_at][1] <= teacher_index:
            continue
        result.insert(insert_at, (student_index, teacher_index))
        used_student.add(student_index)
        used_teacher.add(teacher_index)
    return result


def _extract_observation(
    tokenizer: Any,
    scaffold,
    messages: list[dict],
    connector_ids: list[int],
    *,
    last_token_id: int,
    context: str,
) -> tuple[str, dict]:
    """Recover observation text using the student template, then verify token-exactly."""
    sentinel_message = agent_prompt.observation_message(scaffold, _OBS_SENTINEL)
    sentinel_ids = agent_prompt.render_turn_delta(
        tokenizer,
        messages,
        sentinel_message,
        last_token_id=last_token_id,
        tools=scaffold.tools,
    )
    sentinel_text = tokenizer.decode(sentinel_ids, skip_special_tokens=False)
    marker_at = sentinel_text.find(_OBS_SENTINEL)
    if marker_at < 0:
        raise ValueError(f"{context}: observation sentinel did not survive template rendering")
    prefix = sentinel_text[:marker_at]
    suffix = sentinel_text[marker_at + len(_OBS_SENTINEL) :]

    actual = tokenizer.decode(connector_ids, skip_special_tokens=False)
    if not actual.startswith(prefix) or (suffix and not actual.endswith(suffix)):
        raise ValueError(
            f"{context}: masked connector does not match the student chat template "
            f"(prefix={prefix!r}, suffix={suffix!r}, actual edges={actual[:80]!r}...{actual[-80:]!r})"
        )
    stop = len(actual) - len(suffix) if suffix else len(actual)
    observation = actual[len(prefix) : stop]
    obs_message = agent_prompt.observation_message(scaffold, observation)

    rerendered = agent_prompt.render_turn_delta(
        tokenizer,
        messages,
        obs_message,
        last_token_id=last_token_id,
        tools=scaffold.tools,
    )
    if rerendered != connector_ids:
        mismatch = next(
            (
                i
                for i, (left, right) in enumerate(zip(rerendered, connector_ids))
                if left != right
            ),
            min(len(rerendered), len(connector_ids)),
        )
        raise ValueError(
            f"{context}: recovered observation is not token-exact at offset {mismatch}; "
            f"rendered={len(rerendered)} stored={len(connector_ids)}"
        )
    return observation, obs_message


def _rebuild_canonical_teacher_trajectory(
    sample: Sample,
    bridge: TokenIdBridge,
    student_tokenizer: Any,
    teacher_tokenizer: Any,
    scaffold,
    initial_messages: list[dict],
    student_prompt_length: int,
    teacher_prompt_ids: list[int],
    *,
    context: str,
    partition_student_anchors: bool = False,
    reasoning_effort: str | None = None,
) -> TeacherTrajectory:
    """Re-render every role with the Teacher template and align exact token spans."""
    response_ids = list(sample.tokens[student_prompt_length:])
    mask = np.asarray(sample.loss_mask, dtype=bool)
    runs = _mask_runs(mask)
    if not runs or not runs[0][0]:
        raise ValueError(f"{context}: canonical response must start with an assistant run")

    teacher_ids = list(teacher_prompt_ids)
    teacher_prompt_length = len(teacher_ids)
    student_messages = list(initial_messages)
    teacher_messages = list(initial_messages)
    scored_positions: list[int] = []
    student_scored_positions: list[int] = []
    teacher_assistant_positions: list[int] = []
    assistant_turns = 0
    forced_anchor_reasons: dict[int, int] = {}

    for run_index, (trainable, start, end) in enumerate(runs):
        if not trainable:
            continue
        assistant_turns += 1
        run_ids = response_ids[start:end]
        if not run_ids:
            raise ValueError(f"{context}: empty assistant run {run_index}")
        observation_id = student_tokenizer.convert_tokens_to_ids("<|observation|>")
        last_is_boundary = run_ids[-1] in {
            student_tokenizer.eos_token_id,
            observation_id,
        }
        assistant_ids = run_ids[:-1] if last_is_boundary else run_ids
        assistant_text = student_tokenizer.decode(
            assistant_ids, skip_special_tokens=False
        )
        teacher_assistant = _canonical_assistant_message(
            assistant_text,
            scaffold,
            context=f"{context}: trainable run {run_index}",
        )

        observation = None
        student_observation = None
        has_following_turn = run_index + 2 < len(runs)
        if has_following_turn:
            next_trainable, obs_start, obs_end = runs[run_index + 1]
            following_trainable = runs[run_index + 2][0]
            if next_trainable or not following_trainable:
                raise ValueError(
                    f"{context}: unexpected mask-run sequence near run {run_index}"
                )
            _, student_observation = _extract_observation(
                student_tokenizer,
                scaffold,
                student_messages,
                response_ids[obs_start:obs_end],
                last_token_id=run_ids[-1],
                context=f"{context}: connector after run {run_index}",
            )
            observation = student_observation

        (
            assistant_delta_ids,
            assistant_delta_text,
            connector_ids,
            connector_text,
            prompt_drop,
        ) = _template_turn_deltas(
            teacher_tokenizer,
            teacher_assistant,
            observation,
            context=f"{context}: trainable run {run_index}",
            reasoning_effort=reasoning_effort,
        )
        if prompt_drop:
            # An empty-reasoning turn re-uses the position of the generation
            # prompt's opening <think> for the closing </think> it emits instead.
            del teacher_ids[len(teacher_ids) - prompt_drop :]
            teacher_prompt_length = min(teacher_prompt_length, len(teacher_ids))
        candidate_ids = list(assistant_delta_ids)
        candidate_text = assistant_delta_text
        if connector_ids:
            connector_offsets = _encode_with_offsets(
                teacher_tokenizer,
                connector_text,
                connector_ids,
                context=f"{context}: connector after run {run_index}",
            )
            first_end = connector_offsets[0][1]
            candidate_ids.append(connector_ids[0])
            candidate_text += connector_text[:first_end]

        aligned = _align_canonical_turn(
            student_tokenizer,
            teacher_tokenizer,
            bridge,
            run_ids,
            candidate_ids,
            candidate_text,
            context=f"{context}: trainable run {run_index}",
        )
        if partition_student_anchors:
            # 1: Student-generated reasoning prefix supplied by the Teacher
            # template; 2: Student-only structural tool newline; 3: generated
            # observation stop boundary.  Generic tokenizer N<->M mismatches
            # receive reason 0 below.
            reasoning_prefix = student_tokenizer(
                "\n<think>", add_special_tokens=False
            )["input_ids"]
            if run_ids[: len(reasoning_prefix)] == reasoning_prefix:
                for offset in range(len(reasoning_prefix)):
                    forced_anchor_reasons[start + offset] = 1
            omitted_offsets, _ = _student_tool_call_policy(
                student_tokenizer,
                scaffold,
                run_ids,
                normalize_tool_template=True,
                mask_pre_tool_content=False,
                context=f"{context}: anchor classification run {run_index}",
            )
            for offset in omitted_offsets:
                forced_anchor_reasons[start + offset] = 2
            if (
                last_is_boundary
                and run_ids[-1] == observation_id
                and not _bridge_has_protocol_pairs(student_tokenizer, bridge)
            ):
                # With protocol pairs on, <|observation|> is Teacher-supervised
                # against <|im_end|> ("end the turn now") instead of anchored.
                forced_anchor_reasons[end - 1] = 3
            aligned = [
                pair
                for pair in aligned
                if start + pair[0] not in forced_anchor_reasons
            ]
        teacher_start = len(teacher_ids) - teacher_prompt_length
        student_scored_positions.extend(start + pair[0] for pair in aligned)
        scored_positions.extend(teacher_start + pair[1] for pair in aligned)
        # The assistant delta is exactly what the Teacher would have generated for
        # this turn; the connector that follows is context it only reads.
        teacher_assistant_positions.extend(
            range(teacher_start, teacher_start + len(assistant_delta_ids))
        )

        teacher_ids.extend(assistant_delta_ids)
        teacher_messages.append(teacher_assistant)
        student_messages.append(
            {"role": "assistant", "content": assistant_text}
        )
        if observation is not None:
            teacher_ids.extend(connector_ids)
            teacher_messages.append(observation)
            student_messages.append(student_observation)

    # Independent, full-history render: this is the fail-closed proof that the
    # incrementally assembled sequence is exactly the official Teacher template.
    official_ids, _ = _render_template(
        teacher_tokenizer,
        teacher_messages,
        tools=scaffold.tools,
        add_generation_prompt=False,
        reasoning_effort=reasoning_effort,
    )
    if official_ids != teacher_ids:
        mismatch = next(
            (
                index
                for index, (left, right) in enumerate(zip(official_ids, teacher_ids))
                if left != right
            ),
            min(len(official_ids), len(teacher_ids)),
        )
        raise ValueError(
            f"{context}: incremental canonical trajectory differs from official "
            f"Teacher template at token {mismatch}; official={len(official_ids)} "
            f"incremental={len(teacher_ids)}"
        )

    positions = np.asarray(scored_positions, dtype=np.int32)
    student_positions = np.asarray(student_scored_positions, dtype=np.int32)
    if positions.size == 0 or positions.size != student_positions.size:
        raise ValueError(f"{context}: canonical trajectory has no valid aligned positions")
    if (
        np.any(positions[1:] <= positions[:-1])
        or np.any(student_positions[1:] <= student_positions[:-1])
        or int(positions[-1]) >= len(teacher_ids) - teacher_prompt_length
        or int(student_positions[-1]) >= sample.response_length
        or not np.all(mask[student_positions])
    ):
        raise ValueError(f"{context}: canonical scored positions are invalid")

    trainable = int(mask.sum())
    aligned_count = int(positions.size)
    alignment_rate = aligned_count / max(trainable, 1)
    minimum_rate = float(os.environ.get("OPD_TEACHER_MIN_ALIGNMENT_RATE", "0.90"))
    if not 0.0 < minimum_rate <= 1.0:
        raise ValueError(
            f"{context}: OPD_TEACHER_MIN_ALIGNMENT_RATE must be in (0, 1], "
            f"got {minimum_rate}"
        )
    if alignment_rate < minimum_rate and not partition_student_anchors:
        raise ValueError(
            f"{context}: canonical Student/Teacher alignment rate "
            f"{alignment_rate:.6f} is below the required {minimum_rate:.6f}"
        )
    stats: dict[str, int | float] = {
        "assistant_turns": assistant_turns,
        "student_trainable_tokens_before_alignment": trainable,
        "student_aligned_tokens": aligned_count,
        "student_unaligned_tokens": trainable - aligned_count,
        "teacher_response_tokens": len(teacher_ids) - teacher_prompt_length,
        "teacher_context_only_tokens": (
            len(teacher_ids) - teacher_prompt_length - aligned_count
        ),
        "semantic_alignment_rate": alignment_rate,
        "minimum_required_alignment_rate": minimum_rate,
        "teacher_reasoning_effort": reasoning_effort or "template_default",
    }
    anchor_positions = None
    anchor_reasons = None
    if partition_student_anchors:
        trainable_positions = np.flatnonzero(mask).astype(np.int32)
        anchor_positions = np.setdiff1d(
            trainable_positions, student_positions, assume_unique=True
        ).astype(np.int32, copy=False)
        anchor_reasons = np.asarray(
            [forced_anchor_reasons.get(int(position), 0) for position in anchor_positions],
            dtype=np.int8,
        )
        stats.update(
            {
                "student_anchor_tokens": int(anchor_positions.size),
                "student_anchor_tokenizer_or_template_mismatch": int(
                    np.count_nonzero(anchor_reasons == 0)
                ),
                "student_anchor_reasoning_prefix": int(
                    np.count_nonzero(anchor_reasons == 1)
                ),
                "student_anchor_structural_newline": int(
                    np.count_nonzero(anchor_reasons == 2)
                ),
                "student_anchor_observation_boundary": int(
                    np.count_nonzero(anchor_reasons == 3)
                ),
            }
        )
    dense_positions = np.asarray(teacher_assistant_positions, dtype=np.int32)
    if dense_positions.size == 0 or np.any(dense_positions[1:] <= dense_positions[:-1]):
        raise ValueError(f"{context}: Teacher assistant positions are invalid")
    if int(dense_positions[-1]) >= len(teacher_ids) - teacher_prompt_length:
        raise ValueError(f"{context}: Teacher assistant positions run past the response")
    stats["teacher_assistant_tokens"] = int(dense_positions.size)
    return TeacherTrajectory(
        teacher_ids,
        teacher_prompt_length,
        positions,
        student_positions,
        stats,
        anchor_positions,
        anchor_reasons,
        dense_positions,
    )


def rebuild_teacher_trajectory(
    sample: Sample,
    bridge: TokenIdBridge,
    teacher_model: str,
    *,
    context: str = "offline teacher trajectory",
    preserve_teacher_generation_prefix: bool = False,
    canonicalize_teacher_template: bool = False,
    mask_student_format_tokens: bool = False,
    normalize_student_tool_template: bool = False,
    mask_student_pre_tool_content: bool = False,
    partition_student_anchors: bool = False,
    teacher_reasoning_effort: str | None = None,
) -> TeacherTrajectory:
    """Return teacher-template input IDs and positions for student trainable rows."""
    if sample.response_length <= 0:
        raise ValueError(f"{context}: response_length={sample.response_length}")
    if sample.loss_mask is None or len(sample.loss_mask) != sample.response_length:
        raise ValueError(f"{context}: loss_mask is not response-aligned")
    if len(sample.tokens) < sample.response_length:
        raise ValueError(f"{context}: response is longer than the complete token sequence")

    bridge_student_model, bridge_teacher_model = _bridge_models(bridge)
    requested_teacher = str(Path(teacher_model).expanduser().resolve())
    recorded_teacher = str(Path(bridge_teacher_model).expanduser().resolve())
    if requested_teacher != recorded_teacher:
        raise ValueError(
            f"{context}: teacher template model {requested_teacher} does not match "
            f"the token bridge teacher {recorded_teacher}"
        )

    student_tokenizer = _load_tokenizer(bridge_student_model)
    teacher_tokenizer = _load_tokenizer(teacher_model)
    scaffold = load_scaffold()
    metadata = sample.metadata or {}
    problem_statement = metadata.get("problem_statement")
    if not isinstance(problem_statement, str):
        problem_statement = (metadata.get("ds") or {}).get("problem_statement")
    if not isinstance(problem_statement, str):
        raise ValueError(f"{context}: metadata has no problem_statement")
    workdir = metadata.get("workdir") or "/testbed"
    messages = agent_prompt.initial_messages(scaffold, problem_statement, workdir)

    # Prove that the metadata/scaffold still reconstructs the exact Phase-1 prompt.
    student_prompt_ids, _ = agent_prompt.render_prompt_tokens(
        student_tokenizer, messages, tools=scaffold.tools
    )
    student_prompt_length = len(sample.tokens) - sample.response_length
    stored_student_prompt = list(sample.tokens[:student_prompt_length])
    if student_prompt_ids != stored_student_prompt:
        mismatch = next(
            (
                i
                for i, (left, right) in enumerate(
                    zip(student_prompt_ids, stored_student_prompt)
                )
                if left != right
            ),
            min(len(student_prompt_ids), len(stored_student_prompt)),
        )
        raise ValueError(
            f"{context}: reconstructed Student prompt differs at token {mismatch}; "
            f"rendered={len(student_prompt_ids)} stored={len(stored_student_prompt)}"
        )

    if teacher_reasoning_effort is None:
        # Preserve the historical path byte-for-byte when no explicit effort is
        # requested. This also keeps standard/online OPD completely untouched.
        teacher_prompt_ids, _ = agent_prompt.render_prompt_tokens(
            teacher_tokenizer, messages, tools=scaffold.tools
        )
    else:
        teacher_prompt_ids, _ = _render_template(
            teacher_tokenizer,
            messages,
            tools=scaffold.tools,
            add_generation_prompt=True,
            reasoning_effort=teacher_reasoning_effort,
        )
    if preserve_teacher_generation_prefix and canonicalize_teacher_template:
        raise ValueError(
            f"{context}: native-prefix replay and canonical Teacher template are "
            "mutually exclusive"
        )
    if mask_student_format_tokens and not preserve_teacher_generation_prefix:
        raise ValueError(
            f"{context}: Student format masking requires the native Teacher "
            "generation prefix"
        )
    if (normalize_student_tool_template or mask_student_pre_tool_content) and not (
        preserve_teacher_generation_prefix and mask_student_format_tokens
    ):
        raise ValueError(
            f"{context}: Student tool-template normalization and pre-tool masking "
            "require native Teacher generation-prefix replay plus Student format masking"
        )
    if canonicalize_teacher_template:
        return _rebuild_canonical_teacher_trajectory(
            sample,
            bridge,
            student_tokenizer,
            teacher_tokenizer,
            scaffold,
            messages,
            student_prompt_length,
            teacher_prompt_ids,
            context=context,
            partition_student_anchors=partition_student_anchors,
            reasoning_effort=teacher_reasoning_effort,
        )
    teacher_ids = list(teacher_prompt_ids)
    if not preserve_teacher_generation_prefix:
        teacher_ids = _truncate_after_last_assistant(
            teacher_ids, teacher_tokenizer, context=f"{context}: initial prompt"
        )
    teacher_prompt_length = len(teacher_ids)

    response_ids = list(sample.tokens[student_prompt_length:])
    mask = np.asarray(sample.loss_mask, dtype=bool)
    runs = _mask_runs(mask)
    scored_positions: list[int] = []
    student_scored_positions: list[int] = []
    student_reasoning_prefix = student_tokenizer(
        "\n<think>", add_special_tokens=False
    )["input_ids"]
    if preserve_teacher_generation_prefix and not student_reasoning_prefix:
        raise ValueError(f"{context}: Student reasoning prefix tokenized to an empty sequence")
    student_format_ids: set[int] = set()
    if mask_student_format_tokens:
        for token in _STUDENT_FORMAT_TOKENS:
            token_id = student_tokenizer.convert_tokens_to_ids(token)
            if token_id is not None and token_id != student_tokenizer.unk_token_id:
                student_format_ids.add(int(token_id))
        if not student_format_ids:
            raise ValueError(f"{context}: no Student format token ids were resolved")

    skipped_reasoning_prefix_tokens = 0
    masked_format_tokens = 0
    omitted_tool_structure_tokens = 0
    masked_pre_tool_content_tokens = 0

    for run_index, (trainable, start, end) in enumerate(runs):
        run_ids = response_ids[start:end]
        if trainable:
            mapped_run_ids = run_ids
            student_offsets = list(range(start, end))
            if preserve_teacher_generation_prefix:
                prefix_size = len(student_reasoning_prefix)
                if run_ids[:prefix_size] == student_reasoning_prefix:
                    mapped_run_ids = run_ids[prefix_size:]
                    student_offsets = student_offsets[prefix_size:]
                    skipped_reasoning_prefix_tokens += prefix_size
                elif not mask_student_format_tokens:
                    actual = student_tokenizer.decode(
                        run_ids[:prefix_size], skip_special_tokens=False
                    )
                    raise ValueError(
                        f"{context}: trainable run {run_index} does not start with the "
                        f"Student reasoning prefix '\\n<think>' (decoded={actual!r})"
                    )
                if not mapped_run_ids:
                    raise ValueError(
                        f"{context}: trainable run {run_index} contains only the "
                        "Student reasoning prefix"
                    )

            omitted_offsets, additionally_masked_offsets = _student_tool_call_policy(
                student_tokenizer,
                scaffold,
                run_ids,
                normalize_tool_template=normalize_student_tool_template,
                mask_pre_tool_content=mask_student_pre_tool_content,
                context=f"{context}: trainable run {run_index}",
            )
            omitted_student_positions = {start + offset for offset in omitted_offsets}
            additionally_masked_student_positions = {
                start + offset for offset in additionally_masked_offsets
            }
            omitted_tool_structure_tokens += len(omitted_student_positions)
            masked_pre_tool_content_tokens += len(
                additionally_masked_student_positions - omitted_student_positions
            )
            mapped = bridge.map_numpy(
                mapped_run_ids, context=f"{context}: trainable run {run_index}"
            ).tolist()
            for token_id, mapped_id, student_position in zip(
                mapped_run_ids, mapped, student_offsets, strict=True
            ):
                if student_position in omitted_student_positions:
                    continue
                teacher_position = len(teacher_ids) - teacher_prompt_length
                teacher_ids.append(mapped_id)
                if mask_student_format_tokens and int(token_id) in student_format_ids:
                    masked_format_tokens += 1
                    continue
                if student_position in additionally_masked_student_positions:
                    continue
                scored_positions.append(teacher_position)
                student_scored_positions.append(student_position)

            # The final assistant run has no following observation, and a final masked
            # run can be a context-truncated connector that no future token depends on.
            if run_index + 1 >= len(runs) or run_index + 2 >= len(runs):
                continue
            next_trainable, obs_start, obs_end = runs[run_index + 1]
            following_trainable = runs[run_index + 2][0]
            if next_trainable or not following_trainable:
                raise ValueError(f"{context}: unexpected mask-run sequence near run {run_index}")

            assistant_content = student_tokenizer.decode(
                run_ids, skip_special_tokens=False
            )
            _, obs_message = _extract_observation(
                student_tokenizer,
                scaffold,
                messages,
                response_ids[obs_start:obs_end],
                last_token_id=run_ids[-1],
                context=f"{context}: connector after run {run_index}",
            )
            teacher_delta = agent_prompt.render_turn_delta(
                teacher_tokenizer,
                messages,
                obs_message,
                last_token_id=teacher_ids[-1],
                tools=scaffold.tools,
            )
            if not preserve_teacher_generation_prefix:
                teacher_delta = _truncate_after_last_assistant(
                    teacher_delta,
                    teacher_tokenizer,
                    context=f"{context}: teacher connector after run {run_index}",
                )
            teacher_ids.extend(teacher_delta)
            messages.append({"role": "assistant", "content": assistant_content})
            messages.append(obs_message)

    positions = np.asarray(scored_positions, dtype=np.int32)
    student_positions = np.asarray(student_scored_positions, dtype=np.int32)
    excluded = int(mask.sum()) - int(positions.size)
    minimum_excluded = skipped_reasoning_prefix_tokens + masked_format_tokens
    if excluded < minimum_excluded:
        raise ValueError(
            f"{context}: mapped {positions.size} trainable tokens, but exclusion "
            f"accounting requires at least {minimum_excluded} of {int(mask.sum())}"
        )
    if positions.size and (
        np.any(positions[1:] <= positions[:-1])
        or int(positions[-1]) >= len(teacher_ids) - teacher_prompt_length
    ):
        raise ValueError(f"{context}: teacher scored positions are invalid")
    if student_positions.size != positions.size or (
        student_positions.size
        and (
            np.any(student_positions[1:] <= student_positions[:-1])
            or int(student_positions[-1]) >= sample.response_length
            or not np.all(mask[student_positions])
        )
    ):
        raise ValueError(f"{context}: Student scored positions are invalid")
    stats = {
        "assistant_turns": sum(1 for trainable, _, _ in runs if trainable),
        "student_trainable_tokens_before_alignment": int(mask.sum()),
        "student_aligned_tokens": int(student_positions.size),
        "student_unaligned_tokens": int(mask.sum()) - int(student_positions.size),
        "teacher_response_tokens": len(teacher_ids) - teacher_prompt_length,
        "teacher_context_only_tokens": (
            len(teacher_ids) - teacher_prompt_length - int(positions.size)
        ),
        "semantic_alignment_rate": int(student_positions.size) / max(int(mask.sum()), 1),
        "student_reasoning_prefix_tokens_skipped": skipped_reasoning_prefix_tokens,
        "student_format_tokens_masked": masked_format_tokens,
        "student_tool_structure_tokens_omitted": omitted_tool_structure_tokens,
        "student_pre_tool_content_tokens_masked": masked_pre_tool_content_tokens,
        "normalize_student_tool_template": bool(normalize_student_tool_template),
        "mask_student_pre_tool_content": bool(mask_student_pre_tool_content),
    }
    return TeacherTrajectory(
        teacher_ids,
        teacher_prompt_length,
        positions,
        student_positions,
        stats,
    )


def finalize_native_reasoning_prefix_artifact(
    sample: Sample, *, context: str = "offline teacher trajectory"
) -> int:
    """Mask Student-only reasoning prefixes and compact their sparse snapshots.

    ``reward_func`` stages the retained Student positions without mutating the
    sample so an HTTP retry can rebuild the same request.  Call this only after
    the teacher response has been successfully post-processed.
    """
    return finalize_teacher_position_alignment_artifact(sample, context=context)


def finalize_teacher_position_alignment_artifact(
    sample: Sample, *, context: str = "offline teacher trajectory"
) -> int:
    """Persist one staged Student/Teacher position alignment after scoring."""
    staged = sample.opd_teacher_student_scored_positions
    if staged is None:
        return 0
    if sample.loss_mask is None or len(sample.loss_mask) != sample.response_length:
        raise ValueError(f"{context}: loss_mask is not response-aligned")

    old_mask = np.asarray(sample.loss_mask, dtype=bool)
    old_positions = np.flatnonzero(old_mask).astype(np.int32)
    selected = np.asarray(staged, dtype=np.int32)
    if selected.ndim != 1 or (
        selected.size and np.any(selected[1:] <= selected[:-1])
    ):
        raise ValueError(f"{context}: staged Student positions are not strictly increasing")
    row_indices = np.searchsorted(old_positions, selected)
    if (
        selected.size == 0
        or np.any(row_indices >= old_positions.size)
        or not np.array_equal(old_positions[row_indices], selected)
    ):
        raise ValueError(f"{context}: staged Student positions are not a loss_mask subset")

    ids = sample.student_topk_ids
    if isinstance(ids, list):
        ids = np.concatenate(ids) if ids else np.empty((0, 0), dtype=np.int32)
    ids = np.asarray(ids)
    if ids.ndim != 2 or ids.shape[0] != old_positions.size:
        raise ValueError(
            f"{context}: student_topk_ids rows {ids.shape} do not match "
            f"the original {old_positions.size} trainable positions"
        )
    sample.student_topk_ids = np.ascontiguousarray(ids[row_indices])

    if sample.student_topk_logprobs is not None:
        logprobs = sample.student_topk_logprobs
        if isinstance(logprobs, list):
            logprobs = (
                np.concatenate(logprobs)
                if logprobs
                else np.empty((0, ids.shape[1]), dtype=np.float16)
            )
        logprobs = np.asarray(logprobs)
        if logprobs.shape != ids.shape:
            raise ValueError(
                f"{context}: student_topk_logprobs shape {logprobs.shape} "
                f"!= student_topk_ids shape {ids.shape}"
            )
        sample.student_topk_logprobs = np.ascontiguousarray(logprobs[row_indices])

    new_mask = np.zeros(sample.response_length, dtype=np.int8)
    new_mask[selected] = 1
    sample.loss_mask = new_mask.tolist()
    skipped = int(old_positions.size - selected.size)
    sample.metadata = dict(sample.metadata or {})
    mode = sample.opd_teacher_alignment_mode or "native_reasoning_prefix_v1"
    stats = dict(sample.opd_teacher_alignment_stats or {})
    stats["student_skipped_tokens"] = skipped
    if mode == "canonical_template_v1":
        sample.metadata.update(
            {
                "opd_teacher_canonical_template": True,
                "opd_teacher_canonical_template_schema": 1,
                "opd_teacher_canonical_alignment": stats,
            }
        )
    elif mode == "native_reasoning_prefix_v1":
        sample.metadata.update(
            {
                "opd_teacher_native_reasoning_prefix": True,
                "opd_teacher_native_reasoning_prefix_schema": 1,
                "opd_teacher_native_reasoning_prefix_skipped_tokens": skipped,
            }
        )
    elif mode == "teacher_template_student_tokens_v1":
        normalized_tool_template = bool(
            stats.get("normalize_student_tool_template", False)
        )
        masked_pre_tool_content = bool(
            stats.get("mask_student_pre_tool_content", False)
        )
        sample.metadata.update(
            {
                "opd_teacher_native_reasoning_prefix": True,
                "opd_teacher_template_student_tokens": True,
                "opd_teacher_template_student_tokens_schema": (
                    2 if normalized_tool_template or masked_pre_tool_content else 1
                ),
                "opd_teacher_normalize_student_tool_template": normalized_tool_template,
                "opd_teacher_mask_student_pre_tool_content": masked_pre_tool_content,
                "opd_teacher_template_student_tokens_alignment": stats,
            }
        )
    else:
        raise ValueError(f"{context}: unknown Teacher alignment mode {mode!r}")
    sample.opd_teacher_student_scored_positions = None
    sample.opd_teacher_alignment_mode = None
    sample.opd_teacher_alignment_stats = None
    return skipped


def finalize_cross_tokenizer_anchor_artifact(
    sample: Sample, *, context: str = "offline teacher trajectory"
) -> int:
    """Split Phase-1 Student rows into exact Teacher rows and fallback anchors.

    Unlike :func:`finalize_teacher_position_alignment_artifact`, this isolated
    schema deliberately keeps the original ``loss_mask``.  Exact one-to-one
    rows are consumed by the cached Teacher KL, while its trainable complement
    is persisted as the rollout Student distribution used by the anchor KL.
    """
    import torch

    if sample.opd_teacher_alignment_mode != "canonical_template_v1":
        raise ValueError(
            f"{context}: cross-tokenizer anchors require canonical_template_v1, "
            f"got {sample.opd_teacher_alignment_mode!r}"
        )
    staged = sample.opd_teacher_student_scored_positions
    if staged is None:
        raise ValueError(f"{context}: canonical Student/Teacher positions are missing")
    if sample.loss_mask is None or len(sample.loss_mask) != sample.response_length:
        raise ValueError(f"{context}: loss_mask is not response-aligned")

    trainable_positions = np.flatnonzero(
        np.asarray(sample.loss_mask, dtype=bool)
    ).astype(np.int32)
    teacher_positions = np.asarray(staged, dtype=np.int32)
    if teacher_positions.ndim != 1 or (
        teacher_positions.size
        and np.any(teacher_positions[1:] <= teacher_positions[:-1])
    ):
        raise ValueError(f"{context}: Teacher positions are not strictly increasing")
    teacher_rows = np.searchsorted(trainable_positions, teacher_positions)
    if (
        teacher_positions.size == 0
        or np.any(teacher_rows >= trainable_positions.size)
        or not np.array_equal(trainable_positions[teacher_rows], teacher_positions)
    ):
        raise ValueError(f"{context}: Teacher positions are not a loss_mask subset")
    is_teacher = np.zeros(trainable_positions.size, dtype=bool)
    is_teacher[teacher_rows] = True
    anchor_rows = np.flatnonzero(~is_teacher)
    anchor_positions = trainable_positions[anchor_rows]
    staged_anchor_positions = sample.opd_teacher_student_anchor_positions
    staged_anchor_reasons = sample.opd_teacher_student_anchor_reasons
    if staged_anchor_positions is None or staged_anchor_reasons is None:
        raise ValueError(f"{context}: canonical anchor classification is missing")
    staged_anchor_positions = np.asarray(staged_anchor_positions, dtype=np.int32)
    staged_anchor_reasons = np.asarray(staged_anchor_reasons, dtype=np.int8)
    if not np.array_equal(anchor_positions, staged_anchor_positions):
        raise ValueError(f"{context}: staged anchor positions do not match the complement")
    if staged_anchor_reasons.shape != anchor_positions.shape:
        raise ValueError(f"{context}: staged anchor reasons are not position-aligned")

    ids = sample.student_topk_ids
    if isinstance(ids, list):
        ids = np.concatenate(ids) if ids else np.empty((0, 0), dtype=np.int32)
    ids = np.asarray(ids)
    logprobs = sample.student_topk_logprobs
    if isinstance(logprobs, list):
        logprobs = (
            np.concatenate(logprobs)
            if logprobs
            else np.empty((0, ids.shape[1] if ids.ndim == 2 else 0), dtype=np.float16)
        )
    logprobs = np.asarray(logprobs)
    expected_rows = trainable_positions.size
    if ids.ndim != 2 or ids.shape[0] != expected_rows:
        raise ValueError(
            f"{context}: student_topk_ids shape {ids.shape} does not match "
            f"{expected_rows} trainable positions"
        )
    if logprobs.shape != ids.shape:
        raise ValueError(
            f"{context}: student_topk_logprobs shape {logprobs.shape} "
            f"!= student_topk_ids shape {ids.shape}"
        )
    if not np.isfinite(logprobs).all():
        raise ValueError(f"{context}: student anchor logprobs contain NaN/Inf")

    # Existing rollout diagnostics remain row-aligned with the Teacher cache.
    sample.student_topk_ids = np.ascontiguousarray(ids[teacher_rows])
    sample.student_topk_logprobs = np.ascontiguousarray(logprobs[teacher_rows])
    sample.student_anchor_positions = torch.from_numpy(anchor_positions.copy())
    sample.student_anchor_topk_ids = torch.from_numpy(
        np.ascontiguousarray(ids[anchor_rows], dtype=np.int32)
    )
    sample.student_anchor_topk_logprobs = torch.from_numpy(
        np.ascontiguousarray(logprobs[anchor_rows], dtype=np.float16)
    )
    # Reason 0 is deliberately conservative: the position failed the proven
    # exact 1:1, equal-byte canonical alignment.  More detailed labels are
    # audit metadata only and must never change the loss partition.
    sample.student_anchor_reason = torch.from_numpy(staged_anchor_reasons.copy())
    # This is also a staging hint for dynamic-cache compaction, whose Teacher
    # response contains only the exact aligned rows.
    sample.teacher_candidate_positions = torch.from_numpy(teacher_positions.copy())
    sample.offline_opd_cross_tokenizer_anchor_sparse = True

    stats = dict(sample.opd_teacher_alignment_stats or {})
    stats.update(
        {
            "teacher_positions": int(teacher_positions.size),
            "student_anchor_positions": int(anchor_positions.size),
            "partition_trainable_positions": int(trainable_positions.size),
            "student_anchor_reason_unaligned_exact_1to1": int(
                np.count_nonzero(staged_anchor_reasons == 0)
            ),
        }
    )
    sample.metadata = dict(sample.metadata or {})
    sample.metadata.update(
        {
            "opd_teacher_canonical_template": True,
            "opd_teacher_canonical_template_schema": 2,
            "opd_teacher_canonical_alignment": stats,
            "offline_opd_cross_tokenizer_anchor_sparse": True,
            "offline_opd_cross_tokenizer_anchor_schema": 1,
            "offline_opd_cross_tokenizer_anchor_alignment": stats,
        }
    )
    sample.opd_teacher_student_scored_positions = None
    sample.opd_teacher_student_anchor_positions = None
    sample.opd_teacher_student_anchor_reasons = None
    sample.opd_teacher_alignment_mode = None
    sample.opd_teacher_alignment_stats = None
    return int(anchor_positions.size)


