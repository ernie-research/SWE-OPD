"""Rebuild an offline trajectory with the teacher's chat template.

Phase-1 agent trajectories contain verbatim student-generated tokens, interleaved
with non-trainable tool-observation connectors rendered by the *student* chat
template.  A cross-tokenizer teacher must not consume those student connectors:
the GLM-4.5-Air and GLM-5.2 templates differ in their tool-response whitespace and
generation-prompt suffix.

This module is deliberately opt-in from the offline Phase-2 scorer.  It keeps every
student-generated token (mapped one-to-one through ``TokenIdBridge``), re-renders
only the masked connectors with the teacher tokenizer, and returns the teacher
positions corresponding to the original trainable rows.  Standard/online OPD is
therefore unchanged.
"""

